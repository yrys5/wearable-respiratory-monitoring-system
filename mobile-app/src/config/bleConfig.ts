export const SAMPLE_BUFFER_WINDOW_MS = 60000;

export const BLE_CONFIG = {
  DEVICE_NAME_PREFIX: "01ST",
  PRIMARY_STRAIN_CHANNEL: "n1",
  SERVICE_UUID: "00000000-CC7A-482A-984A-7F2ED5B3E58F",
  STRAIN_GAUGE_CHARACTERISTIC_UUID: "0000A001-8E22-4541-9D4C-21EDAE82ED19",
  CONTROL_CHARACTERISTIC_UUID: "0000A002-8E22-4541-9D4C-21EDAE82ED19",
  SCAN_TIMEOUT_MS: 10000,
  SAMPLE_BUFFER_SIZE,
} as const;

const UUID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function hasConfiguredBleUuids() {
  return (
    UUID_PATTERN.test(BLE_CONFIG.SERVICE_UUID.trim()) &&
    UUID_PATTERN.test(BLE_CONFIG.STRAIN_GAUGE_CHARACTERISTIC_UUID.trim()) &&
    UUID_PATTERN.test(BLE_CONFIG.CONTROL_CHARACTERISTIC_UUID.trim()) &&
    BLE_CONFIG.STRAIN_GAUGE_CHARACTERISTIC_UUID.toLowerCase() !==
      BLE_CONFIG.CONTROL_CHARACTERISTIC_UUID.toLowerCase()
  );
}
